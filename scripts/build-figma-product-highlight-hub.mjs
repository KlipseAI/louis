import { execFileSync } from "node:child_process";
import { readFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { atomicWriteBatch } from "./lib/atomic-output.mjs";

// Highlight hub(`/highlight` 앱 화면)의 5열 카드 그리드 Auto Layout 구조를 생성물로 고정한다.
// 이 구조는 라이브(정본 파일)에서 한 번 손으로 복구됐지만 생성기가 없어 재빌드 시 재현되지 않았다.
// 여기서 만드는 renderer는 install node id로 프레임을 찾아 layout 속성만 멱등적으로 다시 박는다
// (파괴적 재생성이 아니라 reconcile) — 이미 올바른 라이브에 돌려도 no-op이다.
//
// 새 브라우저 측정은 필요 없다. 그리드 기하가 제품 소스에서 파생된다:
//   body width 1596 = main card 1628 − 좌우 padding 16×2
//   card side 309.6 = (1596 − gap 12 × (5−1)) / 5
const repoRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const lockPath = resolve(repoRoot, "migration/product-evidence.lock.json");
const planPath = resolve(repoRoot, "figma/product-highlight-hub.plan.json");
const drawPath = resolve(repoRoot, "figma/product-highlight-hub.draw.js");
const templatePath = resolve(repoRoot, "scripts/templates/figma-product-highlight-hub-renderer.js");
const productRoot = process.env.KLIPSE_PRODUCT_REPO ?? "/Users/sejunki/klipse-web";
const checkOnly = process.argv.includes("--check");
const fail = (message) => { throw new Error(`[figma-product-highlight-hub] ${message}`); };
const commit = JSON.parse(readFileSync(lockPath, "utf8")).productCommit;

const sourceQuote = (path, line, expected) => {
  const command = `git -C ${productRoot} show ${commit}:${path}`;
  const source = execFileSync("git", ["-C", productRoot, "show", `${commit}:${path}`], {
    encoding: "utf8",
    maxBuffer: 32 * 1024 * 1024,
  });
  const quote = source.split("\n")[line - 1] ?? "";
  if (quote !== expected) fail(`source quote drift ${path}:${line}: ${JSON.stringify(quote)}`);
  return { command, path, line, quote };
};

const HIGHLIGHT = "apps/web/components/scenes/highlightSceneStyles.ts";

// 파생 기하 — 소스가 바뀌면 아래 assert가 깨진다.
const mainCardWidth = 1628;
const mainPaddingInline = 16;
const gridGap = 12;
const columns = 5;
const bodyWidth = mainCardWidth - mainPaddingInline * 2;
const cardSide = (bodyWidth - gridGap * (columns - 1)) / columns;
if (bodyWidth !== 1596) fail(`derived body width changed: ${bodyWidth}`);
if (cardSide !== 309.6) fail(`derived card side changed: ${cardSide}`);

const plan = {
  $comment: "Generated by scripts/build-figma-product-highlight-hub.mjs. Do not edit by hand.",
  $evidenceClass: "product-only measured Figma scene repair; /highlight desktop hub 5-column card grid",
  productCommit: commit,
  context: { id: "desktop-1920x1080-dark", route: "/highlight", viewport: { width: 1920, height: 1080 } },
  sourceEvidence: [
    sourceQuote(HIGHLIGHT, 877, '    "[display:grid]",'),
    sourceQuote(HIGHLIGHT, 879, '    "[gap:12px]",'),
    sourceQuote(HIGHLIGHT, 882, '    "min-[1800px]:[grid-template-columns:repeat(5,_1fr)]",'),
    sourceQuote(HIGHLIGHT, 1094, '    "[width:100%]",'),
    sourceQuote(HIGHLIGHT, 1096, '    "[margin:40px_auto_0]",'),
    sourceQuote(HIGHLIGHT, 1097, '    "[padding-bottom:200px]",'),
    sourceQuote(HIGHLIGHT, 1111, '    "[margin-left:6px]",'),
    sourceQuote(HIGHLIGHT, 2270, '    "[&:not(.tw-hs-188)]:[width:400px]!",'),
    sourceQuote(HIGHLIGHT, 2272, '    "[&:not(.tw-hs-188)]:[height:140px]!",'),
    sourceQuote(HIGHLIGHT, 2274, '    "[padding:8px]!",'),
    sourceQuote(HIGHLIGHT, 2275, '    "[gap:8px]!",'),
    sourceQuote(HIGHLIGHT, 2276, '    "[border-radius:20px]!",'),
  ],
  figma: {
    // 정본 파일 OlYKERKOkgbxBEEoXGZW2c. install id로 찾아 reconcile한다.
    screenId: "29:3",
    viewportId: "498:36",
    headingId: "498:37",
    gridId: "498:38",
    cardIds: ["29:19", "29:24", "29:29", "29:34", "29:39"],
    uploadId: "134:588",
    names: {
      viewport: "history viewport · product Auto Layout",
      heading: "history heading · Auto Layout",
      grid: "history grid · 5 columns · Auto Layout wrap",
    },
  },
  layout: {
    viewport: { width: mainCardWidth, height: 1003, x: 0, y: 53, mode: "VERTICAL", padding: [40, mainPaddingInline, 200, mainPaddingInline], gap: gridGap },
    heading: { width: bodyWidth, height: 24, mode: "HORIZONTAL", gap: 6 },
    grid: { width: bodyWidth, mode: "HORIZONTAL", wrap: true, gap: gridGap, crossGap: gridGap, columns },
    card: { width: cardSide, height: cardSide },
    upload: { width: 400, height: 140, x: 620, y: 908, radius: 20, padding: 8, gap: 8 },
  },
};

const runnerPlan = structuredClone(plan);
runnerPlan.sourceEvidence = plan.sourceEvidence.map(({ path, line, quote }) => ({ path, line, quote }));
const draw = `// Generated by scripts/build-figma-product-highlight-hub.mjs. Do not edit by hand.\nconst PLAN=${JSON.stringify(runnerPlan)};\n${readFileSync(templatePath, "utf8")}`;
const outputs = [
  { absolute: planPath, expected: `${JSON.stringify(plan, null, 2)}\n` },
  { absolute: drawPath, expected: draw },
];
if (checkOnly) {
  for (const output of outputs) {
    if (readFileSync(output.absolute, "utf8") !== output.expected) fail(`generated output drift: ${output.absolute.slice(repoRoot.length + 1)}`);
  }
} else {
  atomicWriteBatch(outputs);
}
console.log(`[figma-product-highlight-hub] ${checkOnly ? "checked" : "built"} @ ${commit.slice(0, 8)}: ${columns}-column grid · card ${cardSide} · body ${bodyWidth}`);
